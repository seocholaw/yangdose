"""취득가액 종류 매핑 테스트"""
import pytest
from yangdose.mappings import 취득가액종류_매핑, 취득가액종류


class Test_증여_취득가액_매핑:
    """증여일 때 엑셀 취득가액 종류 → 양도코리아 2단계 매핑"""

    def test_감정가액은_시가평가액(self):
        결과 = 취득가액종류_매핑("증여", "감정가액")
        assert 결과 == 취득가액종류.시가평가액

    def test_매매사례가액은_시가평가액(self):
        결과 = 취득가액종류_매핑("증여", "매매사례가액")
        assert 결과 == 취득가액종류.시가평가액

    def test_환산가액은_보충적평가액(self):
        결과 = 취득가액종류_매핑("증여", "환산가액")
        assert 결과 == 취득가액종류.보충적평가액

    def test_공백_제거(self):
        결과 = 취득가액종류_매핑("증여", "  감정가액  ")
        assert 결과 == 취득가액종류.시가평가액

    def test_알수없는_값_에러(self):
        with pytest.raises(ValueError, match="알 수 없는 취득가액 종류"):
            취득가액종류_매핑("증여", "없는가액")


