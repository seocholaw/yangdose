"""부속토지 모델 및 토지등급 판정 테스트"""

import pytest
from datetime import date
from yangdose.models import (
    토지등급이력, 토지등급_판정, 공시지가, 이월과세정보, 부속토지,
)


# ──────────────────────────────────────────────
# 토지등급 판정 테스트
# ──────────────────────────────────────────────

class Test_토지등급_판정:
    """토지대장 이력 기반 토지등급 산출 테스트 — 이순인 사례 (매곡리 155)"""

    @pytest.fixture
    def 매곡리_이력(self):
        """토지대장 스크린샷 기반 등급이력."""
        return [
            토지등급이력(date(1980, 7, 1), 25),
            토지등급이력(date(1984, 7, 1), 109),
            토지등급이력(date(1990, 1, 1), 115),
            토지등급이력(date(1991, 1, 1), 119),
            토지등급이력(date(1992, 1, 1), 122),
            토지등급이력(date(1993, 1, 1), 125),
            토지등급이력(date(1994, 1, 1), 130),
            토지등급이력(date(1995, 1, 1), 133),
        ]

    def test_기준일_현재_등급(self, 매곡리_이력):
        """1990-08-30 현재 등급 = 115 (1990.01.01 수정 값)"""
        결과 = 토지등급_판정(매곡리_이력, 취득일=date(1977, 11, 8))
        assert 결과["기준일_현재"] == 115

    def test_기준일_직전_등급(self, 매곡리_이력):
        """1990-08-30 직전 등급 = 109 (1984.07.01 수정 값)"""
        결과 = 토지등급_판정(매곡리_이력, 취득일=date(1977, 11, 8))
        assert 결과["기준일_직전"] == 109

    def test_취득당시_1985이전_취득(self, 매곡리_이력):
        """1985.01.01 이전 취득 → 1985.01.01 현재 등급 = 109"""
        결과 = 토지등급_판정(매곡리_이력, 취득일=date(1977, 11, 8))
        assert 결과["취득당시"] == 109

    def test_취득당시_1985이후_취득(self, 매곡리_이력):
        """1991.06.15 취득 → 해당일 현재 등급 = 119"""
        결과 = 토지등급_판정(매곡리_이력, 취득일=date(1991, 6, 15))
        assert 결과["취득당시"] == 119

    def test_취득당시_1990_01_01_정확히(self, 매곡리_이력):
        """1990.01.01 취득 → 등급 = 115"""
        결과 = 토지등급_판정(매곡리_이력, 취득일=date(1990, 1, 1))
        assert 결과["취득당시"] == 115

    def test_빈_이력_에러(self):
        with pytest.raises(ValueError, match="비어 있습니다"):
            토지등급_판정([], 취득일=date(1977, 11, 8))

    def test_정렬되지_않은_이력도_처리(self):
        """역순으로 넣어도 동일 결과."""
        이력 = [
            토지등급이력(date(1990, 1, 1), 115),
            토지등급이력(date(1984, 7, 1), 109),
            토지등급이력(date(1980, 7, 1), 25),
        ]
        결과 = 토지등급_판정(이력, 취득일=date(1977, 11, 8))
        assert 결과["기준일_현재"] == 115
        assert 결과["기준일_직전"] == 109
        assert 결과["취득당시"] == 109


# ──────────────────────────────────────────────
# 부속토지 모델 테스트
# ──────────────────────────────────────────────

class Test_부속토지:
    """이순인 사례 기반 부속토지 데이터 모델 테스트"""

    def test_이순인_매곡리_155(self):
        """스크린샷 데이터로 부속토지 생성."""
        토지 = 부속토지(
            토지번호=1,
            소재지="충청남도 아산시 탕정면 매곡리 155",
            양도가액=189_510_750,
            공시지가=공시지가(양도당시=214_100, 취득당시=7_500),
            토지등급_기준일_현재=115,
            토지등급_기준일_직전=109,
            토지등급_취득당시=109,
            이월과세=이월과세정보(
                증여인_취득일=date(1997, 11, 8),
                증여인_취득원인="일반취득",
            ),
        )
        assert 토지.양도가액 == 189_510_750
        assert 토지.공시지가.양도당시 == 214_100
        assert 토지.공시지가.취득당시 == 7_500
        assert 토지.토지등급_기준일_현재 == 115
        assert 토지.토지등급_기준일_직전 == 109
        assert 토지.토지등급_취득당시 == 109
        assert 토지.이월과세.증여인_취득일 == date(1997, 11, 8)
        assert 토지.이월과세.증여인_취득원인 == "일반취득"
