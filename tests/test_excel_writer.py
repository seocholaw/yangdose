"""엑셀 토지별입력 행 생성 테스트"""

from datetime import date
from yangdose.models import 부속토지, 공시지가, 이월과세정보
from yangdose.excel_writer import 토지별입력_행
from yangdose.excel_columns import 토지별입력시트열 as 열


class Test_토지별입력_행_이월과세:
    """이월과세 시 증여 필드가 자동으로 채워지는지 확인"""

    def _이순인_토지(self):
        return 부속토지(
            토지번호=1,
            소재지="충청남도 아산시 탕정면 매곡리 155",
            양도가액=189_510_750,
            공시지가=공시지가(양도당시=214_100, 취득당시=7_500),
            토지등급_기준일_현재=115,
            토지등급_기준일_직전=109,
            토지등급_취득당시=109,
            이월과세=이월과세정보(
                증여일=date(2026, 1, 30),
                증여인_취득일=date(1977, 11, 8),
                증여인_취득원인="매매",
            ),
        )

    def test_증여일_채움(self):
        행 = 토지별입력_행(
            self._이순인_토지(),
            취득원인="이월과세",
            양도일=date(2026, 2, 4),
            취득일=date(2026, 1, 30),
        )
        assert 행[열.증여일] == date(2026, 1, 30)

    def test_증여인_취득일_채움(self):
        행 = 토지별입력_행(
            self._이순인_토지(),
            취득원인="이월과세",
            양도일=date(2026, 2, 4),
            취득일=date(2026, 1, 30),
        )
        assert 행[열.증여인_취득일] == date(1977, 11, 8)

    def test_증여인_취득원인_채움(self):
        행 = 토지별입력_행(
            self._이순인_토지(),
            취득원인="이월과세",
            양도일=date(2026, 2, 4),
            취득일=date(2026, 1, 30),
        )
        assert 행[열.증여인_취득원인] == "매매"

    def test_이월과세_아닌_경우_증여필드_없음(self):
        토지 = 부속토지(
            토지번호=1,
            소재지="서울시 강남구",
            양도가액=100_000_000,
        )
        행 = 토지별입력_행(
            토지,
            취득원인="일반취득",
            양도일=date(2026, 2, 4),
            취득일=date(2020, 1, 1),
        )
        assert 열.증여일 not in 행
        assert 열.증여인_취득일 not in 행
        assert 열.증여인_취득원인 not in 행
