"""엑셀 토지별입력 시트 데이터 생성

부속토지 모델 → 엑셀 토지별입력 시트 행 데이터를 생성한다.
이월과세인 경우 증여일, 증여인 취득일, 증여인 취득원인을 자동으로 채운다.
"""

from datetime import date
from typing import Optional

from yangdose.models import 부속토지
from yangdose.excel_columns import 토지별입력시트열 as 열


def 토지별입력_행(토지: 부속토지,
                취득원인: str,
                양도일: date,
                취득일: date,
                등기여부: str = "",
                비사업용_여부: str = "",
                감면적용: str = "해당없음",
                감면조항: str = "",
                ) -> dict[int, object]:
    """부속토지 모델로부터 토지별입력 시트 한 행의 데이터를 생성한다.

    Returns:
        {열_인덱스: 값} 딕셔너리
    """
    행 = {
        열.순번: 토지.토지번호,
        열.소재지: 토지.소재지,
        열.등기여부: 등기여부,
        열.취득원인: 취득원인,
        열.양도일: 양도일,
        열.취득일: 취득일,
        열.비사업용_여부: 비사업용_여부,
        열.감면적용: 감면적용,
        열.감면조항: 감면조항,
    }

    # 이월과세 시 증여 관련 필드 자동 채움
    if 토지.이월과세 is not None:
        행[열.증여일] = 토지.이월과세.증여일
        행[열.증여인_취득일] = 토지.이월과세.증여인_취득일
        행[열.증여인_취득원인] = 토지.이월과세.증여인_취득원인

    return 행
