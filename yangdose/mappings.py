"""엑셀 템플릿 값 → 양도코리아 2.0 매핑 정의

엑셀 토지별입력 시트의 값을 양도코리아 입력 화면의 선택지로 변환한다.
"""


# ──────────────────────────────────────────────
# 1단계: 취득원인 선택
# ──────────────────────────────────────────────
class 취득원인:
    일반취득 = "일반취득(매매, 교환, 현물출자 등)"
    상속취득_2년이내 = "2년이내 상속취득"
    상속 = "상속"
    증여 = "증여"
    이월과세 = "이월과세[5년(23.1.1 이후 증여분 부터 10년)이내]"


# ──────────────────────────────────────────────
# 2단계: 취득가액 종류  (취득원인별로 선택지가 다름)
# ──────────────────────────────────────────────
class 취득가액종류:
    # 증여·상속일 때 사용하는 2단계 선택지
    보충적평가액 = "보충적평가액(기준시가)"
    시가평가액 = "시가평가액(매매사례가액, 감정가액 등)"

    # 일반취득일 때 사용하는 2단계 선택지
    실지거래가액 = "실지거래가액"
    환산가액 = "환산가액"


# ──────────────────────────────────────────────
# 엑셀 → 양도코리아 매핑 테이블
# ──────────────────────────────────────────────

# 엑셀 AE열(취득가액 종류) 값 → 양도코리아 2단계 선택값
# 증여/상속 취득원인일 때 적용
_증여상속_취득가액_매핑 = {
    "감정가액":     취득가액종류.시가평가액,
    "매매사례가액":  취득가액종류.시가평가액,
    # 보충적평가액 계열
    "환산가액":     취득가액종류.보충적평가액,
}

# 일반취득일 때는 엑셀 값을 그대로 사용
_일반취득_취득가액_매핑 = {
    "실지거래가액":  취득가액종류.실지거래가액,
    "감정가액":     취득가액종류.실지거래가액,   # 일반취득 시 실거래 계열
    "매매사례가액":  취득가액종류.실지거래가액,
    "환산가액":     취득가액종류.환산가액,
}


def 취득가액종류_매핑(취득원인: str, 엑셀_취득가액종류: str,
                  증여인_취득원인: str = None) -> str:
    """엑셀 취득가액 종류 값을 양도코리아 2단계 선택값으로 변환한다.

    Args:
        취득원인: 취득원인 문자열 (예: "증여", "상속", "일반취득" 등)
        엑셀_취득가액종류: 엑셀 AE열의 값 (예: "감정가액", "실지거래가액" 등)
        증여인_취득원인: 이월과세일 때 증여인의 취득원인 (예: "일반취득", "상속", "증여")

    Returns:
        양도코리아 2단계에서 선택할 값

    Raises:
        ValueError: 매핑되지 않는 값이 입력된 경우
    """
    값 = 엑셀_취득가액종류.strip()

    # 이월과세: 증여인의 취득원인에 따라 매핑이 달라짐
    if 취득원인 in (취득원인_cls.이월과세, "이월과세"):
        if 증여인_취득원인 is None:
            raise ValueError(
                "이월과세일 때는 증여인_취득원인을 지정해야 합니다."
            )
        # 증여인의 취득원인으로 재귀 호출
        return 취득가액종류_매핑(증여인_취득원인, 엑셀_취득가액종류)

    # 증여 또는 상속 계열
    if 취득원인 in (취득원인_cls.증여, 취득원인_cls.상속, 취득원인_cls.상속취득_2년이내,
                   "증여", "상속", "2년이내 상속취득"):
        결과 = _증여상속_취득가액_매핑.get(값)
        if 결과 is None:
            raise ValueError(
                f"증여/상속 취득 시 알 수 없는 취득가액 종류: '{값}'. "
                f"가능한 값: {list(_증여상속_취득가액_매핑.keys())}"
            )
        return 결과

    # 일반취득 계열
    결과 = _일반취득_취득가액_매핑.get(값)
    if 결과 is None:
        raise ValueError(
            f"알 수 없는 취득가액 종류: '{값}'. "
            f"가능한 값: {list(_일반취득_취득가액_매핑.keys())}"
        )
    return 결과


# 클래스 인스턴스 참조용 alias
취득원인_cls = 취득원인
