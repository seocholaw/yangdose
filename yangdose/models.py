class 이월과세정보:
    """이월과세 시 증여인 관련 정보."""
    증여인_취득일: date
    증여인_취득원인: str  # "일반취득", "상속", "증여" 등


# ──────────────────────────────────────────────
# 부속토지 데이터
# ──────────────────────────────────────────────
@dataclass
class 부속토지:
    """엑셀 토지별입력 시트의 한 필지 데이터."""
    토지번호: int
