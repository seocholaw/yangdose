"""부속토지 데이터 모델 및 토지등급 판정 로직

엑셀 템플릿 ↔ 양도코리아 입력에 사용되는 토지 데이터를 정의한다.
"""

from dataclasses import dataclass, field
from datetime import date
from typing import Optional


# ──────────────────────────────────────────────
# 토지등급 이력 (토지대장에서 추출)
# ──────────────────────────────────────────────
@dataclass
class 토지등급이력:
    """토지대장의 등급수정 한 건."""
    수정일: date
    등급: int


def 토지등급_판정(이력: list[토지등급이력],
              취득일: date,
              기준일_현재: date = date(1990, 8, 30),
              ) -> dict[str, Optional[int]]:
    """토지대장 등급이력으로부터 3가지 토지등급을 산출한다.

    Args:
        이력: 등급수정 이력 리스트 (수정일 오름차순 정렬 불필요, 내부에서 정렬)
        취득일: 양도자(또는 증여인)의 실제 취득일
        기준일_현재: 환산기준일 (기본값 1990-08-30)

    Returns:
        {
            "기준일_현재": 기준일 현재 토지등급,
            "기준일_직전": 기준일 직전 토지등급,
            "취득당시": 취득당시 토지등급
                       (1985-01-01 이전 취득분은 1985-01-01 현재 등급 적용),
        }
    """
    if not 이력:
        raise ValueError("토지등급 이력이 비어 있습니다.")

    정렬 = sorted(이력, key=lambda h: h.수정일)

    def _해당등급(기준: date) -> Optional[int]:
        """기준일 이하(<=)인 가장 최근 등급을 반환한다."""
        결과 = None
        for h in 정렬:
            if h.수정일 <= 기준:
                결과 = h.등급
            else:
                break
        return 결과

    def _직전등급(기준: date) -> Optional[int]:
        """기준일 미만(<)인 가장 최근 등급의 '이전' 등급을 반환한다.

        기준일 현재 등급 바로 직전의 수정 등급을 의미한다.
        """
        이전 = None
        현재 = None
        for h in 정렬:
            if h.수정일 <= 기준:
                이전 = 현재
                현재 = h.등급
            else:
                break
        return 이전 if 이전 is not None else 현재

    # 취득당시: 1985-01-01 이전 취득분은 1985-01-01 현재 등급 적용
    취득기준일 = 취득일 if 취득일 >= date(1985, 1, 1) else date(1985, 1, 1)

    return {
        "기준일_현재": _해당등급(기준일_현재),
        "기준일_직전": _직전등급(기준일_현재),
        "취득당시": _해당등급(취득기준일),
    }


# ──────────────────────────────────────────────
# 공시지가
# ──────────────────────────────────────────────
@dataclass
class 공시지가:
    """개별공시지가 (원/㎡)."""
    양도당시: int
    취득당시: int


# ──────────────────────────────────────────────
# 이월과세 정보
# ──────────────────────────────────────────────
