"""양도코리아 2.0 입력 데이터 생성

부속토지 모델 → 양도코리아 프로그램 입력 필드 값을 생성한다.
"""

from datetime import date
from typing import Optional

from yangdose.models import 부속토지
from yangdose.mappings import 취득원인, 취득가액종류_매핑


# ──────────────────────────────────────────────
# 증여인 취득원인 → 양도코리아 선택값 매핑
# ──────────────────────────────────────────────
_증여인_취득원인_매핑 = {
    "매매": "1.일반취득",
    "일반취득": "1.일반취득",
    "교환": "1.일반취득",
    "현물출자": "1.일반취득",
    "상속": "2.상속",
    "증여": "3.증여",
}


def 증여인_취득원인_변환(취득원인_값: str) -> str:
    """증여인의 취득원인을 양도코리아 드롭다운 선택값으로 변환한다."""
    결과 = _증여인_취득원인_매핑.get(취득원인_값)
    if 결과 is None:
        raise ValueError(
            f"알 수 없는 증여인 취득원인: '{취득원인_값}'. "
            f"가능한 값: {list(_증여인_취득원인_매핑.keys())}"
        )
    return 결과


# ──────────────────────────────────────────────
# 양도코리아 입력 데이터 생성
# ──────────────────────────────────────────────

def 이월과세_입력(토지: 부속토지, 증여세_상당액: int = 0) -> dict[str, object]:
    """이월과세 팝업에 입력할 데이터를 생성한다.

    양도코리아 스크린샷 1번 기준:
      - 증여일
      - 증여인의 취득일
      - 증여인의 취득원인 (드롭다운)
      - 증여세 상당액

    Returns:
        양도코리아 필드명: 값 딕셔너리
    """
    if 토지.이월과세 is None:
        raise ValueError("이월과세 정보가 없는 토지입니다.")

    return {
        "증여일": 토지.이월과세.증여일,
        "증여인의 취득일": 토지.이월과세.증여인_취득일,
        "증여인의 취득원인": 증여인_취득원인_변환(토지.이월과세.증여인_취득원인),
        "증여세 상당액": 증여세_상당액,
    }


def 공시지가_입력(토지: 부속토지) -> dict[str, int]:
    """개별공시지가 입력 데이터를 생성한다.

    양도코리아 토지 기본정보 화면의 개별공시지가 테이블에 입력할 값.

    Returns:
        {"양도당시": 원/㎡, "취득당시": 원/㎡}
    """
    if 토지.공시지가 is None:
        raise ValueError("공시지가 정보가 없는 토지입니다.")

    return {
        "양도당시": 토지.공시지가.양도당시,
        "취득당시": 토지.공시지가.취득당시,
    }


def 토지등급_입력(토지: 부속토지) -> dict[str, Optional[int]]:
    """토지등급 입력 데이터를 생성한다.

    양도코리아 토지 기본정보 화면의 토지등급 테이블에 입력할 값.
    1990.01.01 이전 취득분에만 해당.

    Returns:
        {"현재": 등급, "직전": 등급, "취득당시": 등급}
    """
    return {
        "현재": 토지.토지등급_기준일_현재,
        "직전": 토지.토지등급_기준일_직전,
        "취득당시": 토지.토지등급_취득당시,
    }
